#!/usr/bin/env bash
# Disposable nt-bkp-pg only; local Unix socket, PGUSER=postgres.
set -Eeuo pipefail
set -x
postgres --version
pg_dump --version
psql -X -d postgres -v ON_ERROR_STOP=1 -c 'SELECT current_database(), current_user, version();'
createdb demo
psql -X -d demo -v ON_ERROR_STOP=1 <<'SQL'
CREATE TABLE customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE payments (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer NOT NULL REFERENCES customers(id), amount numeric(12,2) NOT NULL CHECK(amount > 0));
INSERT INTO customers(name) VALUES ('Pavel'), ('Anna');
INSERT INTO payments(customer_id,amount) VALUES (1,1250.00),(2,750.50),(1,100.00);
SELECT * FROM customers ORDER BY id;
SELECT * FROM payments ORDER BY id;
SELECT count(*) AS payments, sum(amount) AS total FROM payments;
SQL
mkdir -p /backups
psql -X -At -d demo -c 'SELECT c.id,c.name,p.id,p.amount FROM customers c JOIN payments p ON p.customer_id=c.id ORDER BY p.id' > /backups/before.tsv
